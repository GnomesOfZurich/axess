"""Crafted cases for scripts/lib/workflow_installs.py, run by
scripts/check-workflow-pins-tests.sh.

Each case runs one script through `Installs.script` in a temporary root
holding the files it names, and pins every refusal (with the file it names
and its line), every install found for the job, and every toolchain read.
Run with `python3 -I -B`.
"""

import os
import shutil
import sys
import tempfile

if __name__ == "__main__":
    # Run as a script under -I, which puts no directory on the path: the
    # modules beside this one are found here.
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import workflow_cargo as C
import workflow_installs as I
import workflow_python as Y


def run(script, files):
    root = tempfile.mkdtemp()
    try:
        for name, text in files.items():
            os.makedirs(os.path.dirname(os.path.join(root, name)) or root, exist_ok=True)
            with open(os.path.join(root, name), "w") as f:
                f.write(text)
        refusals = []

        def display(p):
            return os.path.relpath(p, root) if p.startswith(root) else p
        inst = I.Installs(root, lambda p, m: refusals.append((display(p), m)), display)
        found = inst.script(script, I.line_index(script), "w.yml")
        return (refusals, [f.describe() for f in found], inst.toolchains)
    finally:
        shutil.rmtree(root)


