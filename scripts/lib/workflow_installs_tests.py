def properties():
    """Every entry of the reader's tables, each in a script that needs it."""
    failures = []
    for name, table, held in (
            ("PREFIXES", I.PREFIXES, PREFIXES), ("RESERVED", I.RESERVED, RESERVED),
            ("CARGO_VALUE_FLAGS", C.CARGO_VALUE_FLAGS, CARGO_VALUE_FLAGS),
            ("INSTALL_VALUE_FLAGS", C.INSTALL_VALUE_FLAGS, INSTALL_VALUE_FLAGS),
            ("INSTALL_FLAGS", C.INSTALL_FLAGS, INSTALL_FLAGS), ("ROUTES", I.ROUTES, ROUTES),
            ("TASK_RUNNERS", I.TASK_RUNNERS, TASK_RUNNERS), ("RUNNERS", Y.RUNNERS, RUNNERS)):
        if table != held:
            failures.append("%s is not the table the cases hold" % name)

    def refusals(script):
        return [m for _, m in run(script, {})[0]]
    for prefix, flags in sorted(PREFIXES.items()):
        for flag in sorted(flags) + [None]:
            words = prefix + (" %s v" % flag if flag else "") + (" 10" if prefix == "timeout" else "")
            if not any("cargo install without --locked" in m for m in refusals(words + " bash -c 'cargo install a'")):
                failures.append("the command after `%s` is not read" % words)
    for word in sorted(RESERVED):
        script = "%s bash -c 'cargo install a'%s" % (word, "; }" if word == "{" else "")
        if not any("cargo install without --locked" in m for m in refusals(script)):
            failures.append("the command after `%s` is not read" % word)
    for flag in sorted(CARGO_VALUE_FLAGS):
        got = refusals("cargo %s %s install --locked a@1.0.0 b" % (flag, "net.retry=3" if flag == "--config" else "v"))
        if got != ["line 1: no exact version for b (crate@X.Y.Z or --version X.Y.Z)"]:
            failures.append("cargo's own %s takes a value: %r" % (flag, got))
    special = {"--version", "--vers", "--git", "--path", "--index", "--registry"}
    for flag in sorted(INSTALL_VALUE_FLAGS - special):
        got = refusals("cargo install --locked a@1.0.0 %s %s" % (flag, "net.retry=3" if flag == "--config" else "value"))
        if got:
            failures.append("%s takes a value: %r" % (flag, got))
    for flag in sorted(INSTALL_FLAGS):
        got = refusals("cargo install --locked a@1.0.0 %s b" % flag)
        if got != ["line 1: no exact version for b (crate@X.Y.Z or --version X.Y.Z)"]:
            failures.append("%s takes no value: %r" % (flag, got))
    for command, subs in sorted(ROUTES.items()):
        for sub in sorted(subs) if subs else [None]:
            script = command + (" " + sub if sub else "") + " x"
            if not any("an install route the check does not read" in m for m in refusals(script)):
                failures.append("the route `%s` is not refused" % script)
    for name in sorted(TASK_RUNNERS):
        for script in (name + " tools", "sudo " + name, "f() { \"$@\"; }\nf " + name + " tools"):
            if not any("the recipes %s runs are not read" % name in m for m in refusals(script)):
                failures.append("the task runner in `%s` is not refused" % script)
        if refusals("echo " + name):
            failures.append("the word %s as an argument is refused" % name)
    for flag in ("-v", "-vvv", "--verbose", "-q", "--quiet", "-V", "--version", "--list", "--locked", "--offline", "--frozen", "-h", "--help"):
        if not any("cargo install without --locked" in m for m in refusals('"$C" %s install a' % flag)) and flag not in ("--locked", "--frozen"):
            failures.append("cargo's own flag %s does not end the reading of a variable program" % flag)
    if refusals('"$C" --other install a'):
        failures.append("a flag cargo does not have is read as cargo's")
    awks = ["awk", "busybox-awk", "gawk", "mawk", "nawk"]
    for script in [n + " 'BEGIN { system(1) }'" for n in awks] + ["sed e f", "gsed e f", "parallel x", "sem x"]:
        if not refusals(script):
            failures.append("`%s` is not refused" % script)
    for name in sorted(RUNNERS):
        if not Y.python_runs_install("%s(['cargo', 'install'])\n" % name):
            failures.append("a program that calls %s is not read" % name)
    if Y.python_runs_install("run(['cargo', 'install'])\n"):
        failures.append("a program that runs nothing is read as one that does")
